#!/usr/bin/env bash
# Resource-based (adaptive) load balancing: sample web1/web2 CPU load + memory,
# rewrite nginx upstream weights (lower utilization → higher weight), reload nginx.
# Installed on the loadbalancer when LB_ALGORITHM=resource|adaptive.

set -euo pipefail

PROJECT_ROOT="${PROJECT_ROOT:-/opt/automation-alchemy}"
KEY="${PROJECT_ROOT}/keys/id_ed25519"
STATUS_DIR="/var/lib/automation-alchemy"
STATUS_JSON="${STATUS_DIR}/lb-status.json"
SITE="/etc/nginx/sites-available/automation-alchemy-lb"
SSH_OPTS=(-i "${KEY}" -o StrictHostKeyChecking=accept-new -o UserKnownHostsFile=/root/.ssh/known_hosts_ii -o BatchMode=yes -o ConnectTimeout=5)

WEB1=10.10.0.11
WEB2=10.10.0.12

mkdir -p "${STATUS_DIR}" /root/.ssh
chmod 700 /root/.ssh

sample_host() {
  local ip="$1"
  local out
  if ! out="$(ssh "${SSH_OPTS[@]}" "devops@${ip}" bash -s <<'REMOTE'
set -euo pipefail
load1=$(awk '{print $1}' /proc/loadavg)
cores=$(nproc 2>/dev/null || echo 1)
mem_pct=$(awk '/MemTotal:/{t=$2} /MemAvailable:/{a=$2} END{ if(t>0) printf "%.1f", (t-a)*100/t; else print 50 }' /proc/meminfo)
echo "${load1} ${cores} ${mem_pct}"
REMOTE
)"; then
    echo "FAIL"
    return
  fi
  echo "${out}"
}

weight_from_sample() {
  local sample="$1"
  if [[ "${sample}" == FAIL ]] || [[ -z "${sample}" ]]; then
    echo 1
    return
  fi
  local load1 cores mem_pct
  read -r load1 cores mem_pct <<<"${sample}"
  cores="${cores:-1}"
  awk -v load1="${load1}" -v cores="${cores}" -v mem="${mem_pct:-50}" 'BEGIN {
    if (cores < 1) cores = 1
    u = (load1 / cores) * 0.65 + (mem / 100.0) * 0.35
    if (u > 1) u = 1
    if (u < 0) u = 0
    w = int(10 * (1.0 - u) + 1 + 0.5)
    if (w < 1) w = 1
    if (w > 10) w = 10
    print w
  }'
}

s1="$(sample_host "${WEB1}")"
s2="$(sample_host "${WEB2}")"
w1="$(weight_from_sample "${s1}")"
w2="$(weight_from_sample "${s2}")"

if [[ "${w1}" -eq 1 && "${w2}" -eq 1 ]]; then
  w1=5
  w2=5
fi

APPSERVER=10.10.0.20
stamp="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
cat >"${SITE}" <<EOF
# Generated by aa-lb-resource-adapt at ${stamp}
# Do not edit by hand while resource algorithm is active.
# gzip on is already set in /etc/nginx/nginx.conf — only tune types/level here
gzip_comp_level 5;
gzip_min_length 256;
gzip_proxied any;
gzip_types text/plain text/css application/json application/javascript text/xml application/xml image/svg+xml;

upstream app_backend {
    server ${APPSERVER}:3000;
    keepalive 16;
}

upstream web_backends {
    server ${WEB1}:80 weight=${w1};
    server ${WEB2}:80 weight=${w2};
    keepalive 16;
}

server {
    listen 80 default_server;
    listen [::]:80 default_server;
    server_name _;

    location = /lb-status {
        default_type application/json;
        add_header Cache-Control "no-store";
        alias ${STATUS_JSON};
    }

    location /api/ {
        proxy_pass http://app_backend/;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header Connection "";
        proxy_connect_timeout 5s;
        proxy_read_timeout 30s;
        add_header Cache-Control "no-store";
    }

    location / {
        proxy_pass http://web_backends;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header Connection "";
    }
}
EOF

# Escape sample strings for JSON
json_escape() {
  printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'
}

cat >"${STATUS_JSON}" <<EOF
{
  "algorithm": "resource",
  "updatedAt": "${stamp}",
  "upstreams": [
    {"host": "web1", "ip": "${WEB1}", "weight": ${w1}, "sample": "$(json_escape "${s1}")"},
    {"host": "web2", "ip": "${WEB2}", "weight": ${w2}, "sample": "$(json_escape "${s2}")"}
  ]
}
EOF
chmod 644 "${STATUS_JSON}"

nginx -t
systemctl reload nginx
echo "resource adapt: web1=w${w1} (${s1}) web2=w${w2} (${s2})"
